    def test_renderer_semantic_gutter_callouts_and_visible_recall(self):
        with tempfile.TemporaryDirectory() as td:
            td = Path(td)
            md = td / "u1.md"
            out = td / "u1.html"
            md.write_text(
                """# Unidad 1\n\n## Concepto\n\nTexto **clave**.\n\n> [!DEFINITION] Variable\n> Un dato que puede cambiar.\n\n> [!WARNING] Precondición no es validación\n> No confundas una garantía con una comprobación.\n\n> [!EXAM] Formato confirmado para el final\n> Se evalúa con el formato indicado por la cátedra.\n\n> [!RECALL] Sin mirar\n> Explicá qué es una variable.\n""",
                encoding="utf-8",
            )
            cp = subprocess.run(
                [sys.executable, str(RENDER), str(md), str(out), "--kind", "summary", "--course", "Programación I", "--scope", "Unidad 1", "--check"],
                cwd=ROOT,
                text=True,
                capture_output=True,
            )
            self.assertEqual(cp.returncode, 0, cp.stdout + cp.stderr)
            page = out.read_text(encoding="utf-8")
            self.assertIn('class="callout definition"', page)
            self.assertIn('class="callout recall"', page)
            self.assertNotIn('<details class="callout recall">', page)
            self.assertIn('class="callout-body"', page)
            self.assertIn('<div class="callout-title">Definición</div>', page)
            self.assertIn('<p class="term">Variable</p>', page)
            self.assertIn('<div class="callout-title">Cuidado</div>', page)
            self.assertIn('<p class="term">Precondición no es validación</p>', page)
            self.assertIn('<div class="callout-title">Para evaluación</div>', page)
            self.assertIn('<p class="term">Formato confirmado para el final</p>', page)
            self.assertIn('<div class="callout-title">Recuperación</div>', page)
            self.assertIn('<p class="term">Sin mirar</p>', page)
            self.assertIn('class="prompt"', page)
            self.assertIn('class="hint"', page)
            self.assertNotIn('class="toc"', page)
            self.assertIn("Texto <strong>clave</strong>", page)
            self.assertIn('class="book-running-line"', page)
            self.assertIn('class="book-course">Programación I</span>', page)
            self.assertIn('class="study-header"><div class="mark">Capítulo 1</div>', page)
            self.assertIn('class="section-head"><div class="num"></div><h2', page)
            self.assertIn('fonts.googleapis.com', page)

